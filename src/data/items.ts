export function normalById(id: number): ItemInfo | undefined {
  return Normal.find((i) => i.id === id);
}

export function importantById(id: number): ItemInfo | undefined {
  return Important.find((i) => i.id === id);
}

export function nameForNormal(id: number): string {
  return normalById(id)?.name ?? `#${id}`;
}

export function nameForImportant(id: number): string {
  return importantById(id)?.name ?? `#${id}`;
}
